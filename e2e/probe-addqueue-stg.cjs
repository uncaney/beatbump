const { chromium } = require("playwright");
const URL = process.argv[2] || "https://staging-music.ekaii.fr";
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const browser = await chromium.launch({ channel: "chrome", args: ["--autoplay-policy=no-user-gesture-required", "--ignore-certificate-errors", "--host-resolver-rules=MAP *.ekaii.fr 127.0.0.1"] });
  const ctx = await browser.newContext({ extraHTTPHeaders: { "X-Ytm-Harness": "1" },  ignoreHTTPSErrors: true, viewport: { width: 1280, height: 900 } });
  const page = await ctx.newPage();
  page.on("console", (m) => { if (["error", "warning"].includes(m.type())) console.log("CONSOLE", m.type(), m.text().slice(0, 220)); });
  page.on("pageerror", (e) => console.log("PAGEERROR", String(e).slice(0, 220)));
  page.on("response", (r) => { if (/get_queue|next\.json/.test(r.url())) console.log("RESP", r.status(), r.url().slice(URL.length, URL.length + 70)); });
  await page.goto(URL + "/search/" + encodeURIComponent("daft punk") + "?filter=all", { waitUntil: "networkidle", timeout: 60000 });
  await page.getByText(/Song\s*•/).first().click(); await sleep(3000);
  const q0 = await page.evaluate(() => (window.localStorage, document.querySelectorAll('[data-testid="queue-row"]').length));
  await page.locator("main [aria-label=\"Plus d'options\"]").nth(1).click({ timeout: 5000 }); await sleep(700);
  await page.getByText(/Ajouter à la file/i).first().click({ timeout: 4000 }); await sleep(1500);
  console.log("TOASTS", JSON.stringify(await page.locator(".alert").allInnerTexts().catch(() => [])));
  await page.keyboard.press("Escape"); await sleep(300);
  await page.locator("main [aria-label=\"Plus d'options\"]").nth(2).click({ timeout: 5000 }); await sleep(700);
  await page.getByText(/Lire ensuite/i).first().click({ timeout: 4000 }); await sleep(1500);
  console.log("TOASTS2", JSON.stringify(await page.locator(".alert").allInnerTexts().catch(() => [])));
  await browser.close();
})().catch((e) => { console.log("FATAL", String(e)); process.exit(1); });
